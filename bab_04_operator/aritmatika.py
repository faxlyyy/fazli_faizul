print(7 - 3)     # 4       Pengurangan
print(7 * 3)     # 21      Perkalian
print(7 / 3)     # 2.333…  Pembagian
print(7 // 3)    # 2       Pembagian bulat
print(7 % 3)     # 1       Modulus (sisa)
print(7 ** 3)    # 343     Pangkat

